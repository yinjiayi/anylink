const ssoCallbackPath = "/+CSCOE+/sso/callback"
const ssoFinalPath = "/+CSCOE+/saml_ac_login.html"
const ssoDonePath = "/+CSCOE+/sso/done"

type ssoProvider interface {
	AuthorizationURL(state, nonce, verifier string) string
	Authenticate(ctx context.Context, code, nonce, verifier string) (string, error)
}

type ssoGateway struct {
	store       *ssoStore
	loadConfig  func(string) (sso.Config, error)
	authorize   func(string, string, sso.Config) (string, error)
	newProvider func(context.Context, sso.Config) (ssoProvider, error)
	complete    func(http.ResponseWriter, *http.Request, *AuthSession)
	record      func(dbdata.UserActLog, string)
}

var browserSSO = &ssoGateway{
	store: newSSOStore(), loadConfig: dbdata.GetSSOConfig, authorize: dbdata.AuthorizeSSO,
	newProvider: func(ctx context.Context, c sso.Config) (ssoProvider, error) { return sso.NewProvider(ctx, c) },
	complete:    CreateSession,
	record:      func(ua dbdata.UserActLog, agent string) { dbdata.UserActLogIns.Add(ua, agent) },
}

func isBrowserSSOGroup(name string) bool {
	if name == "" || dbdata.GetXdb() == nil {
		return false
	}
	g := &dbdata.Group{}
	if dbdata.One("Name", name, g) != nil {
		return false
	}
	return g.Auth["type"] == "oidc" || g.Auth["type"] == "oauth2"
}

func ssoHeaders(w http.ResponseWriter) {
	w.Header().Set("Cache-Control", "no-store")
	w.Header().Set("Pragma", "no-cache")
	w.Header().Set("Referrer-Policy", "no-referrer")
	w.Header().Set("X-Content-Type-Options", "nosniff")
}

func ssoError(w http.ResponseWriter, status int) {
	ssoHeaders(w)
	http.Error(w, "SSO authentication could not be completed. Restart VPN login.", status)
}

func hasSSOCapability(cr *ClientRequest, capability string) bool {
	for _, v := range cr.Capabilities.AuthMethods {
		if v == capability {
			return true
		}
	}
	return false
}

// begin also handles the auth-reply generated by the client's group selector.
// It never falls back to local passwords for an SSO group.
func (g *ssoGateway) begin(w http.ResponseWriter, r *http.Request, cr *ClientRequest, c sso.Config) {
	ssoHeaders(w)
	if err := c.Validate(); err != nil {
		ssoError(w, http.StatusServiceUnavailable)
		return
	}
	internal := hasSSOCapability(cr, "single-sign-on-v2")
	external := hasSSOCapability(cr, "single-sign-on-external-browser")
	key, keyErr := sso.ParseSTRAPKey(r.Header.Get("X-AnyConnect-STRAP-DH-Pubkey"))
	mode := c.BrowserMode
	if mode == "" || mode == "auto" {
		if external && keyErr == nil {
			mode = "external"
		} else {
			mode = "internal"
		}
	}
	if (mode == "internal" && !internal) || (mode == "external" && !external) {
		ssoError(w, http.StatusBadRequest)
		return
	}
	if mode == "external" && keyErr != nil {
		ssoError(w, http.StatusBadRequest)
		return
	}
	tx, err := g.store.create(*cr, c, mode, key)
	if err != nil {
		ssoError(w, http.StatusServiceUnavailable)
		return
	}
	login := c.PublicURL + "/+CSCOE+/sso/start?tx=" + tx.ID
	method := "<auth-method>single-sign-on-v2</auth-method>"
	if mode == "external" {
		method += "<auth-method>single-sign-on-external-browser</auth-method>"
	}
	esc := func(s string) string { var b bytes.Buffer; _ = xml.EscapeText(&b, []byte(s)); return b.String() }
	w.Header().Set("Content-Type", "application/xml; charset=utf-8")
	fmt.Fprintf(w, `<?xml version="1.0" encoding="UTF-8"?>
<config-auth client="vpn" type="auth-request" aggregate-auth-version="2">
<opaque is-for="sg"><tunnel-group>%s</tunnel-group><group-alias>%s</group-alias>%s<sso-session-id>%s</sso-session-id></opaque>
<auth id="main"><title>Single sign-on</title><message>Complete sign-in in your browser.</message>
<sso-v2-login>%s</sso-v2-login><sso-v2-login-final>%s</sso-v2-login-final>
<sso-v2-token-cookie-name>acSamlv2Token</sso-v2-token-cookie-name>`, esc(cr.GroupSelect), esc(cr.GroupSelect), method, tx.Challenge, esc(login), esc(c.PublicURL+ssoFinalPath))
	if mode == "external" {
		fmt.Fprint(w, "<sso-v2-browser-mode>external</sso-v2-browser-mode>")
	}
	fmt.Fprint(w, `<form><input type="sso" name="sso-token"></input></form></auth></config-auth>`)
}

func ssoBrowserCookie(state string) string {
	// State is generated by this server; unknown user input must not cause slicing panics.
	if len(state) != 64 {
		return "anylink-sso-invalid"
	}
	return "anylink-sso-browser-" + state[:16]
}

func (g *ssoGateway) start(w http.ResponseWriter, r *http.Request) {
	ssoHeaders(w)
	tx, err := g.store.claimStart(r.URL.Query().Get("tx"))
	if err != nil {
		ssoError(w, http.StatusBadRequest)
		return
	}
	keep := false
	defer func() {
		if !keep {
			g.store.remove(tx.ID)
		}
	}()
	// Discovery is performed only after a real VPN handshake, with a deadline.
	ctx, cancel := context.WithTimeout(r.Context(), 15*time.Second)
	defer cancel()
	tx.Provider, err = g.newProvider(ctx, tx.Config)
	if err != nil {
		ssoError(w, http.StatusBadGateway)
		return
	}
	for _, target := range []*string{&tx.State, &tx.BrowserSecret, &tx.Nonce, &tx.Verifier} {
		*target, err = ssoRandom()
		if err != nil {
			ssoError(w, http.StatusInternalServerError)
			return
		}
	}
	if err := g.store.started(tx); err != nil {
		ssoError(w, http.StatusBadRequest)
		return
	}
	http.SetCookie(w, &http.Cookie{Name: ssoBrowserCookie(tx.State), Value: tx.BrowserSecret,
		Path: "/+CSCOE+/sso/", Secure: true, HttpOnly: true, SameSite: http.SameSiteLaxMode, MaxAge: int(ssoLifetime.Seconds())})
	keep = true
	http.Redirect(w, r, tx.Provider.AuthorizationURL(tx.State, tx.Nonce, tx.Verifier), http.StatusFound)
}

func (g *ssoGateway) callback(w http.ResponseWriter, r *http.Request) {
	ssoHeaders(w)
	q := r.URL.Query()
	state := q.Get("state")
	if len(q["state"]) != 1 || len(q["code"]) > 1 || len(q["error"]) > 1 {
		ssoError(w, http.StatusBadRequest)
		return
	}
	cookie, err := r.Cookie(ssoBrowserCookie(state))
	if err != nil {
		ssoError(w, http.StatusBadRequest)
		return
	}
	tx, err := g.store.callback(state, cookie.Value)
	if err != nil {
		ssoError(w, http.StatusBadRequest)
		return
	}
	http.SetCookie(w, &http.Cookie{Name: cookie.Name, Path: "/+CSCOE+/sso/", Secure: true, HttpOnly: true, SameSite: http.SameSiteLaxMode, MaxAge: -1})
	keep := false
	defer func() {
		if !keep {
			g.store.remove(tx.ID)
		}
	}()
	if q.Get("error") != "" || q.Get("code") == "" {
		ssoError(w, http.StatusUnauthorized)
		return
	}
	ctx, cancel := context.WithTimeout(r.Context(), 15*time.Second)
	defer cancel()
	subject, err := tx.Provider.Authenticate(ctx, q.Get("code"), tx.Nonce, tx.Verifier)
	if err != nil {
		ssoError(w, http.StatusUnauthorized)
		return
	}
	username, err := g.authorize(tx.Client.GroupSelect, subject, tx.Config)
	if err != nil {
		ssoError(w, http.StatusForbidden)
		return
	}
	tx, err = g.store.issue(tx.ID, subject, username)
	if err != nil {
		ssoError(w, http.StatusBadRequest)
		return
	}
	if tx.Mode == "external" {
		payload, err := sso.EncryptBrowserToken(tx.PublicKey, tx.Ticket)
		if err != nil {
			ssoError(w, http.StatusInternalServerError)
			return
		}
		keep = true
		http.Redirect(w, r, "http://localhost:29786/api/sso/"+url.PathEscape(payload)+"?return="+url.QueryEscape(tx.Config.PublicURL+ssoDonePath), http.StatusFound)
		return
	}
	http.SetCookie(w, &http.Cookie{Name: "acSamlv2Token", Value: tx.Ticket, Path: "/", Secure: true, HttpOnly: true, SameSite: http.SameSiteLaxMode, MaxAge: int(ssoTicketLifetime.Seconds())})
	http.SetCookie(w, &http.Cookie{Name: "anylink-sso-finish", Value: "1", Path: ssoFinalPath, Secure: true, HttpOnly: true, SameSite: http.SameSiteLaxMode, MaxAge: int(ssoTicketLifetime.Seconds())})
	keep = true
	http.Redirect(w, r, tx.Config.PublicURL+ssoFinalPath, http.StatusFound)
}

func (g *ssoGateway) redeem(w http.ResponseWriter, r *http.Request, cr *ClientRequest, ua *dbdata.UserActLog) {
	ssoHeaders(w)
	tx, err := g.store.redeem(*cr)
	if err != nil {
		ssoError(w, http.StatusUnauthorized)
		return
	}
	username, err := g.authorize(tx.Client.GroupSelect, tx.Subject, tx.Config)
	if err != nil || username != tx.Username {
		ssoError(w, http.StatusForbidden)
		return
	}
	if !lockManager.CheckLocked(username, r.RemoteAddr) {
		ssoError(w, http.StatusTooManyRequests)
		return
	}
	// Device metadata and selected group come from the initiating VPN request.
	client := tx.Client
	client.Auth.Username = username
	client.RemoteAddr = r.RemoteAddr
	ua.Username, ua.GroupName, ua.Info = username, client.GroupSelect, "用户通过 "+strings.ToUpper(tx.Config.Type)+" SSO 登录"
	ua.DeviceType, ua.PlatformVersion = client.DeviceId.DeviceType, client.DeviceId.PlatformVersion
	ua.Status = dbdata.UserAuthSuccess
	if g.record != nil {
		g.record(*ua, client.UserAgent)
	}
	g.complete(w, r, &AuthSession{ClientRequest: &client, UserActLog: ua})
}

func SSODone(w http.ResponseWriter, r *http.Request) {
	ssoHeaders(w)
	w.Header().Set("Content-Security-Policy", "default-src 'none'; frame-ancestors 'none'")
	w.Header().Set("Content-Type", "text/html; charset=utf-8")
	fmt.Fprint(w, "<!doctype html><html><meta charset=\"utf-8\"><title>VPN sign-in</title><p>Browser sign-in is complete. Return to the VPN client to finish connecting.</p></html>")
}
